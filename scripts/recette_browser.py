import argparse
import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

parser = argparse.ArgumentParser(description='Recette navigateur du frontend F1 en mode démonstration uniquement.')
parser.add_argument('--base-url', default='http://127.0.0.1:5173')
parser.add_argument('--output', default='artifacts/browser')
parser.add_argument('--offline-bundle', help='Banc de revue hors ligne, non fourni dans la livraison.')
parser.add_argument('--chromium', help='Exécutable Chromium facultatif.')
parser.add_argument('--harness-runtime', help='Identité du runtime utilisé dans un banc de revue ; ne valide pas le build Vite.')
args = parser.parse_args()
out = Path(args.output)
out.mkdir(parents=True, exist_ok=True)
results, errors, network = [], [], []

def ok(name):
    results.append({'name': name, 'passed': True})
    print('PASS', name)

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, executable_path=args.chromium)
    page = browser.new_page(viewport={'width': 1440, 'height': 1050}, device_scale_factor=1)
    page.set_default_timeout(10000)
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.on('request', lambda r: network.append(r.url))
    if args.offline_bundle:
        css = Path('src/styles.css').read_text() + Path('src/institutional.css').read_text()
        page.set_content('<html lang="fr"><head><meta name="viewport" content="width=device-width,initial-scale=1"><style>' + css + '</style></head><body><div id="root"></div></body></html>')
        page.add_script_tag(content=Path(args.offline_bundle).read_text())
    else:
        page.goto(args.base_url)
    expect(page.get_by_role('button', name='Ouvrir la démonstration')).to_be_visible()
    ok('Connexion de démonstration clairement identifiée')
    page.wait_for_timeout(300)
    page.screenshot(path=str(out/'connexion.png'), full_page=True)
    page.get_by_role('button', name='Ouvrir la démonstration').click()
    expect(page.get_by_role('heading', name='Bonjour, Administrateur A.')).to_be_visible()
    expect(page.locator('.demo-banner')).to_be_visible()
    ok('Entrée, identité fictive et bandeau permanent')
    page.wait_for_timeout(300)
    page.screenshot(path=str(out/'espace-travail.png'), full_page=True)
    page.get_by_role('navigation', name='Navigation principale').get_by_role('button', name='Institutions', exact=True).click()
    expect(page.get_by_role('heading', name='Institutions', exact=True)).to_be_visible()
    expect(page.get_by_role('button', name='Ajouter une institution')).to_be_visible()
    ok('Catalogue institutionnel et commandes visibles pour A')
    expect(page.get_by_role('button',name='Ouvrir Ministère de démonstration A')).to_be_visible()
    page.wait_for_timeout(300)
    page.screenshot(path=str(out/'institutions.png'), full_page=True)
    page.get_by_role('button', name='Ajouter une institution').click()
    dialog=page.get_by_role('dialog')
    expect(dialog).to_be_visible()
    page.get_by_label('Code *', exact=True).fill('QA_F1')
    page.get_by_label('Intitulé *', exact=True).fill('Institution de recette F1')
    dialog.get_by_role('button',name='Vérifier la commande').click()
    expect(dialog.locator('pre')).to_contain_text('QA_F1')
    ok('Relecture explicite de la commande avant écriture')
    dialog.get_by_role('button',name='Confirmer',exact=True).click()
    expect(page.get_by_role('button',name='Ouvrir Institution de recette F1')).to_be_visible()
    ok('Création simulée, fermeture et relecture du catalogue')
    page.get_by_role('button',name='Ouvrir Institution de recette F1').click()
    page.get_by_role('button',name='Modifier',exact=True).click()
    page.get_by_label('Intitulé *',exact=True).fill('Institution F1 renommée')
    page.get_by_label('Motif de modification *').fill('Vérification du contrôle de version et de la relecture.')
    dialog.get_by_role('button',name='Vérifier la commande').click()
    expect(dialog.locator('pre')).to_contain_text('expectedVersion')
    dialog.get_by_role('button',name='Confirmer',exact=True).click()
    expect(page.get_by_role('heading',name='Institution F1 renommée')).to_be_visible()
    ok('Modification avec motif et version attendue')
    page.get_by_role('button',name='Changer le statut',exact=True).click()
    page.get_by_label('Motif *',exact=True).fill('Suspension réversible de recette.')
    dialog.get_by_role('button',name='Vérifier la commande').click()
    dialog.get_by_role('button',name='Confirmer la décision').click()
    expect(page.locator('.detail-card .badge-suspendu')).to_be_visible()
    ok('Changement de statut simulé et fiche actualisée')
    page.get_by_role('navigation',name='Navigation principale').get_by_role('button',name='Rôles et habilitations',exact=True).click()
    page.get_by_role('button',name='Ouvrir Archiviste de démonstration').click()
    page.get_by_role('button',name='Configurer les permissions').click()
    expect(page.get_by_role('dialog')).to_be_visible()
    page.get_by_role('checkbox', name='DOSSIER_CREATE').check()
    page.get_by_label('Motif *',exact=True).fill('Étendre les droits du rôle pendant la recette F1.')
    dialog.get_by_role('button',name='Vérifier la commande').click()
    expect(dialog.locator('pre')).to_contain_text('expectedRoleVersion')
    dialog.get_by_role('button',name='Soumettre la proposition').click()
    page.get_by_role('button',name='Impact & demandes de changement').click()
    page.get_by_role('button',name='Examiner',exact=True).click()
    expect(page.get_by_text('Vous êtes à l’origine de cette demande.',exact=False)).to_be_visible()
    expect(page.get_by_role('button',name='Approuver',exact=True)).to_have_count(0)
    ok('Proposition sur rôle utilisé, pas d’auto-approbation affichée')
    page.get_by_label('Persona de démonstration').select_option('b')
    expect(page.get_by_role('heading',name='Bonjour, Administrateur B.')).to_be_visible()
    page.get_by_role('navigation',name='Navigation principale').get_by_role('button',name='Rôles et habilitations',exact=True).click()
    page.get_by_role('button',name='Ouvrir Archiviste de démonstration').click()
    page.get_by_role('button',name='Impact & demandes de changement').click()
    page.get_by_role('button',name='Examiner',exact=True).click()
    page.get_by_role('button',name='Approuver',exact=True).click()
    page.get_by_label('Motif de votre décision *').fill('Relecture indépendante par B.')
    dialog.get_by_role('button',name='Vérifier la commande').click()
    dialog.get_by_role('button',name='Confirmer',exact=True).click()
    expect(page.locator('.change-detail .badge-applied')).to_be_visible()
    ok('Approbation indépendante simulée et état APPLIED')
    page.wait_for_timeout(300)
    page.screenshot(path=str(out/'gouvernance.png'), full_page=True)
    page.get_by_label('Persona de démonstration').select_option('agent')
    expect(page.get_by_role('heading',name='Bonjour, Agent de recette.')).to_be_visible()
    expect(page.get_by_role('navigation').get_by_role('button',name='Gouvernance',exact=True)).to_have_count(0)
    page.get_by_role('navigation').get_by_role('button',name='Utilisateurs',exact=True).click()
    expect(page.get_by_role('heading',name='Utilisateurs',exact=True)).to_be_visible()
    expect(page.get_by_role('button',name='Ajouter une identité')).to_have_count(0)
    ok('Persona agent : navigation et mutations restreintes')
    page.set_viewport_size({'width':390,'height':844})
    page.get_by_role('button',name='Ouvrir le menu').click()
    expect(page.locator('.sidebar.open')).to_be_visible()
    page.keyboard.press('Escape')
    expect(page.locator('.sidebar.open')).to_have_count(0)
    expect(page.get_by_role('button', name='Ouvrir le menu')).to_be_focused()
    page.get_by_role('button', name='Ouvrir le menu').click()
    page.get_by_role('navigation').get_by_role('button',name='Vue d’ensemble',exact=True).click()
    expect(page.locator('.sidebar.open')).to_have_count(0)
    page.wait_for_timeout(300)
    box=page.locator('.sidebar').bounding_box()
    assert box is None or box['x'] + box['width'] <= 1
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth + 1')
    ok('Affichage mobile 390px, menu clavier Échap/focus et absence de débordement horizontal global')
    page.screenshot(path=str(out/'mobile.png'),full_page=True)
    page.get_by_role('button',name='Se déconnecter').click()
    expect(page.get_by_role('button',name='Ouvrir la démonstration')).to_be_visible()
    expect(page.locator('.sidebar')).to_have_count(0)
    ok('Déconnexion locale efface les vues protégées')
    assert page.evaluate('localStorage.length')==0 if not args.offline_bundle else True
    assert not errors, '\n'.join(errors)
    assert not any('/api/' in u or 'supabase' in u for u in network), network
    ok('Aucune erreur JavaScript non gérée, aucun appel backend dans la démo')
    browser.close()
report={'kind':'offline-ui-smoke' if args.offline_bundle else 'vite-demo-browser','runtime':args.harness_runtime or 'npm-target','results':results,'passed':len(results),'errors':errors,'requests':network,'limitations':'Données simulées. Ne valide pas le backend, le SSO, PostgreSQL ni la sécurité du serveur.'}
(out/'report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2))
print('TOTAL',len(results),'PASS')
